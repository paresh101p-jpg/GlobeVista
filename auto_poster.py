#!/usr/bin/env python3
"""
GlobeVista Auto Poster
Posts daily travel images to Facebook Page (GlobeVista) & Instagram (GlobeVista1)
Caption auto-generated by Gemini Vision - place-specific history + why to visit + hashtags
Schedule: 4:00 PM IST (10:30 UTC) daily via GitHub Actions
"""

import os
import sys
import json
import random
import requests
import base64
import time
from pathlib import Path

# ─── CONFIG ──────────────────────────────────────────────────────────────────
SCRIPT_DIR = Path(__file__).parent

def load_token():
    # GitHub Actions secrets take priority
    token = os.environ.get("FB_PAGE_ACCESS_TOKEN", "").strip()
    if not token:
        token_file = SCRIPT_DIR / "fb_permanent_token.txt"
        if token_file.exists():
            token = token_file.read_text().strip()
    return token

def load_config():
    cfg_file = SCRIPT_DIR / "fb_config.json"
    with open(cfg_file) as f:
        return json.load(f)

def load_gemini_key():
    key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not key:
        key_file = SCRIPT_DIR / "gemini_key.txt"
        if key_file.exists():
            key = key_file.read_text().strip()
    return key

# ─── IMAGE QUEUE ─────────────────────────────────────────────────────────────
def get_next_image():
    queue_file = SCRIPT_DIR / "images_urls.txt"
    backup_file = SCRIPT_DIR / "images_urls_backup.txt"
    used_file = SCRIPT_DIR / "used_urls.txt"

    lines = []
    if queue_file.exists():
        lines = [l.strip().lstrip('\ufeff') for l in queue_file.read_text(encoding='utf-8').splitlines() if l.strip().lstrip('\ufeff')]

    # Refill from backup if empty
    if not lines:
        print("Queue empty — refilling from backup...")
        if backup_file.exists():
            backup = [l.strip().lstrip('\ufeff') for l in backup_file.read_text(encoding='utf-8').splitlines() if l.strip().lstrip('\ufeff')]
            if backup:
                random.shuffle(backup)
                lines = backup
                queue_file.write_text("\n".join(lines) + "\n")
                print(f"Refilled {len(lines)} URLs from backup.")

    if not lines:
        print("ERROR: No images available in queue or backup!")
        sys.exit(1)

    # Pop first URL
    image_url = lines[0]
    remaining = lines[1:]
    queue_file.write_text("\n".join(remaining) + "\n" if remaining else "")

    # Append to used
    with open(used_file, "a") as f:
        f.write(image_url + "\n")

    print(f"Using image: {image_url}")
    print(f"Remaining in queue: {len(remaining)}")
    return image_url

# ─── GEMINI VISION CAPTION ───────────────────────────────────────────────────
def generate_caption(image_url: str, gemini_key: str) -> str:
    """Use Gemini Vision to analyze travel image and generate caption."""

    prompt = """You are a professional travel writer. Analyze this travel destination image carefully.

Write a compelling Instagram/Facebook travel post caption in English with this EXACT structure:

📍 [PLACE NAME]

[2-3 sentences of brief history of this place — when it was built/discovered, its significance, era]

✈️ [2-3 sentences on why you should visit — best season, what to see/experience, unique highlights]

[6-8 highly relevant location-specific hashtags]

RULES:
- Identify the EXACT destination from the image (city, landmark, country)
- Keep total caption between 80-120 words (not counting hashtags)
- Hashtags must be specific to this location (e.g. #EiffelTower #Paris #France not generic #travel)
- English only
- Do NOT use asterisks (*) or bold markdown
- End with hashtags on separate line
- Make it exciting and inspiring for travelers"""

    # Download image to base64
    try:
        resp = requests.get(image_url, timeout=30)
        resp.raise_for_status()
        img_b64 = base64.b64encode(resp.content).decode()
        mime_type = resp.headers.get("Content-Type", "image/jpeg").split(";")[0]
    except Exception as e:
        print(f"WARNING: Could not download image for Gemini Vision: {e}")
        return generate_fallback_caption()

    # Call Gemini API
    api_url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={gemini_key}"
    payload = {
        "contents": [{
            "parts": [
                {"text": prompt},
                {"inline_data": {"mime_type": mime_type, "data": img_b64}}
            ]
        }],
        "generationConfig": {
            "temperature": 0.8,
            "maxOutputTokens": 400
        }
    }

    try:
        r = requests.post(api_url, json=payload, timeout=60)
        r.raise_for_status()
        caption = r.json()["candidates"][0]["content"]["parts"][0]["text"].strip()
        print("✅ Gemini Vision caption generated successfully")
        print(f"Caption preview: {caption[:100]}...")
        return caption
    except Exception as e:
        print(f"WARNING: Gemini Vision failed: {e}")
        return generate_fallback_caption()

def generate_fallback_caption() -> str:
    return """📍 Incredible Destination

This breathtaking place holds centuries of history, culture, and natural beauty waiting to be explored.

✈️ Visit for unforgettable landscapes, rich local traditions, and memories that last a lifetime. The perfect escape for every traveler!

#Travel #Wanderlust #ExploreTheWorld #TravelPhotography #BucketList #TravelGram #WorldTravel #Adventure"""

# ─── FACEBOOK POST ────────────────────────────────────────────────────────────
def post_to_facebook(image_url: str, caption: str, page_id: str, token: str) -> str:
    print("Posting to Facebook Page...")
    url = f"https://graph.facebook.com/v21.0/{page_id}/photos"
    payload = {
        "url": image_url,
        "caption": caption,
        "access_token": token
    }
    r = requests.post(url, data=payload, timeout=60)
    result = r.json()
    if "id" in result:
        post_id = result["id"]
        print(f"✅ Facebook Post ID: {post_id}")
        return post_id
    else:
        print(f"❌ Facebook Error: {result}")
        return None

# ─── INSTAGRAM POST ──────────────────────────────────────────────────────────
def post_to_instagram(image_url: str, caption: str, ig_account_id: str, token: str) -> str:
    print("Posting to Instagram...")

    # Step 1: Create media container
    container_url = f"https://graph.facebook.com/v21.0/{ig_account_id}/media"
    container_payload = {
        "image_url": image_url,
        "caption": caption,
        "access_token": token
    }
    r1 = requests.post(container_url, data=container_payload, timeout=60)
    result1 = r1.json()

    if "id" not in result1:
        print(f"❌ Instagram Container Error: {result1}")
        return None

    container_id = result1["id"]
    print(f"Instagram container created: {container_id}")

    # Step 2: Wait for processing
    time.sleep(5)

    # Step 3: Publish
    publish_url = f"https://graph.facebook.com/v21.0/{ig_account_id}/media_publish"
    publish_payload = {
        "creation_id": container_id,
        "access_token": token
    }
    r2 = requests.post(publish_url, data=publish_payload, timeout=60)
    result2 = r2.json()

    if "id" in result2:
        media_id = result2["id"]
        print(f"✅ Instagram Media ID: {media_id}")
        return media_id
    else:
        print(f"❌ Instagram Publish Error: {result2}")
        return None

# ─── MAIN ────────────────────────────────────────────────────────────────────
def main():
    print("=" * 60)
    print("🌍 GlobeVista Auto Poster Starting...")
    print("=" * 60)

    # Load credentials
    token = load_token()
    config = load_config()
    gemini_key = load_gemini_key()

    if not token:
        print("ERROR: FB_PAGE_ACCESS_TOKEN not found!")
        sys.exit(1)

    page_id = config["fb_page_id"]
    ig_account_id = config["ig_account_id"]

    print(f"FB Page ID: {page_id}")
    print(f"IG Account ID: {ig_account_id}")

    # Get next image
    image_url = get_next_image()

    # Generate caption via Gemini Vision
    print("\nGenerating caption with Gemini Vision...")
    caption = generate_caption(image_url, gemini_key)
    print(f"\nFinal Caption:\n{caption}\n")

    # Post to both platforms
    print("-" * 40)
    fb_post_id = post_to_facebook(image_url, caption, page_id, token)
    print("-" * 40)
    ig_media_id = post_to_instagram(image_url, caption, ig_account_id, token)

    print("\n" + "=" * 60)
    print("📊 POSTING SUMMARY")
    print("=" * 60)
    print(f"Facebook: {'✅ SUCCESS - ' + str(fb_post_id) if fb_post_id else '❌ FAILED'}")
    print(f"Instagram: {'✅ SUCCESS - ' + str(ig_media_id) if ig_media_id else '❌ FAILED'}")
    print("=" * 60)

    if not fb_post_id and not ig_media_id:
        print("Both platforms failed — exiting with error")
        sys.exit(1)

    print("🌍 GlobeVista post complete!")

if __name__ == "__main__":
    main()
